#!/usr/bin/env node
// Generates Android VectorDrawable resources and Kotlin mapping
// from @mdi/svg@<EXPECTED_MDI_VERSION> for the :ha_resources module.
//
// Run:
//   cd ha_resources
//   npm install
//   npm run download:ha-icons

import { readFile, writeFile, readdir, mkdir, rm, copyFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const EXPECTED_MDI_VERSION = '7.4.47';
const REQUIRED_ICONS = ['robot', 'robot-off', 'lightbulb', 'palette', 'script-text'];
const CHUNK_SIZE = 800; // entries per fillN() function in HaIcons.kt
const KOTLIN_PACKAGE = 'com.anadolstudio.ha_resources';

const FALLBACK_DOMAIN_ICONS = {
  automation: 'mdi:robot',
  scene: 'mdi:palette',
  script: 'mdi:script-text',
  light: 'mdi:lightbulb',
  switch: 'mdi:toggle-switch',
  sensor: 'mdi:eye',
  climate: 'mdi:thermostat',
  calendar: 'mdi:calendar',
  person: 'mdi:account',
  weather: 'mdi:weather-partly-cloudy',
  zone: 'mdi:map-marker-radius',
};

const __filename = fileURLToPath(import.meta.url);
const SCRIPT_DIR = dirname(__filename);
const MODULE_DIR = resolve(SCRIPT_DIR, '..');

const NODE_MODULES_MDI_DIR = join(MODULE_DIR, 'node_modules', '@mdi', 'svg');
const SVG_SRC_DIR = join(NODE_MODULES_MDI_DIR, 'svg');

const SVG_OUT_DIR = join(MODULE_DIR, 'svg');
const DRAWABLE_OUT_DIR = join(MODULE_DIR, 'src', 'main', 'res', 'drawable');
const KOTLIN_OUT_DIR = join(MODULE_DIR, 'src', 'main', 'java', 'com', 'anadolstudio', 'ha_resources');
const HA_ICONS_DIR = join(MODULE_DIR, 'ha-icons');
const README_PATH = join(MODULE_DIR, 'README.md');

function fail(msg) {
  console.error(`\n[ha-icons] ERROR: ${msg}\n`);
  process.exit(1);
}

function log(msg) {
  console.log(`[ha-icons] ${msg}`);
}

function sanitizeName(name) {
  return name.toLowerCase().replace(/[^a-z0-9]/g, '_');
}

function extractPathD(svg) {
  // MDI 7.4.47 icons are always a single <path d="..."/>
  // Find d="..." or d='...'
  const m = svg.match(/<path[^>]*\sd\s*=\s*"([^"]+)"/) || svg.match(/<path[^>]*\sd\s*=\s*'([^']+)'/);
  if (!m) return null;
  // Make sure there is exactly one <path ...> in the file
  const pathCount = (svg.match(/<path\b/g) || []).length;
  if (pathCount !== 1) return null;
  return m[1];
}

function escapeXmlAttr(s) {
  return s
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;');
}

function buildVectorDrawable(pathData) {
  return `<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="24"
    android:viewportHeight="24">

    <path
        android:fillColor="@android:color/black"
        android:pathData="${escapeXmlAttr(pathData)}" />
</vector>
`;
}

function escapeKotlinStringLiteral(s) {
  // Map keys are stable mdi:* identifiers (a-z, 0-9, hyphen), no escaping needed in practice.
  // Be defensive anyway.
  return s.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
}

function buildHaIconsKt(entries) {
  // entries: Array<{ haIcon, drawableName }>, already sorted
  const chunks = [];
  for (let i = 0; i < entries.length; i += CHUNK_SIZE) {
    chunks.push(entries.slice(i, i + CHUNK_SIZE));
  }

  let out = '';
  out += `// Generated by scripts/download-ha-icons.mjs from @mdi/svg@${EXPECTED_MDI_VERSION}. Do not edit by hand.\n`;
  out += `@file:Suppress("LongMethod", "LargeClass", "MaxLineLength")\n\n`;
  out += `package ${KOTLIN_PACKAGE}\n\n`;
  out += `object HaIcons {\n`;
  out += `    const val MDI_VERSION: String = "${EXPECTED_MDI_VERSION}"\n\n`;
  out += `    val icons: Map<String, Int> by lazy(LazyThreadSafetyMode.PUBLICATION) {\n`;
  out += `        val m = HashMap<String, Int>(${Math.max(16, entries.length * 2)})\n`;
  for (let i = 0; i < chunks.length; i++) {
    out += `        fill${i}(m)\n`;
  }
  out += `        m\n`;
  out += `    }\n\n`;
  out += `    fun resolve(haIcon: String): Int? = icons[haIcon]\n\n`;
  for (let i = 0; i < chunks.length; i++) {
    out += `    private fun fill${i}(m: MutableMap<String, Int>) {\n`;
    for (const e of chunks[i]) {
      const key = escapeKotlinStringLiteral(e.haIcon);
      out += `        m["${key}"] = R.drawable.${e.drawableName}\n`;
    }
    out += `    }\n`;
    if (i !== chunks.length - 1) out += `\n`;
  }
  out += `}\n`;
  return out;
}

function buildFallbackKt(fallbackMap) {
  let out = '';
  out += `// Generated by scripts/download-ha-icons.mjs. Do not edit by hand.\n\n`;
  out += `package ${KOTLIN_PACKAGE}\n\n`;
  out += `object HaDomainFallbackIcons {\n`;
  out += `    val fallback: Map<String, String> = mapOf(\n`;
  const keys = Object.keys(fallbackMap).sort();
  for (const k of keys) {
    out += `        "${escapeKotlinStringLiteral(k)}" to "${escapeKotlinStringLiteral(fallbackMap[k])}",\n`;
  }
  out += `    )\n\n`;
  out += `    fun resolve(domain: String): String? = fallback[domain]\n`;
  out += `}\n`;
  return out;
}

function buildReadme(iconCount) {
  return `# ha_resources

Android-library module that ships the **full Material Design Icons (MDI)** set
used by Home Assistant frontend, packaged as Android \`VectorDrawable\` resources
plus a generated type-safe Kotlin mapping \`mdi:* -> @DrawableRes Int\`.

- MDI version: **${EXPECTED_MDI_VERSION}** (matches \`@mdi/svg\` in home-assistant/frontend)
- Icons in this build: **${iconCount}**
- Generated at: ${new Date().toISOString()}

## Layout

\`\`\`
ha_resources/
├── build.gradle.kts                 # android-library
├── package.json                     # @mdi/svg@${EXPECTED_MDI_VERSION}
├── scripts/download-ha-icons.mjs    # generator
├── ha-icons/                        # dev metadata (in git)
│   ├── icons_index.json
│   └── ha_domain_fallback_icons.json
├── svg/                             # raw SVG (gitignored; regenerated on each run)
└── src/main/
    ├── AndroidManifest.xml
    ├── res/drawable/                # ic_mdi_<name>.xml  (in git)
    └── java/com/anadolstudio/ha_resources/
        ├── HaIcon.kt
        ├── HaIcons.kt                # generated
        └── HaDomainFallbackIcons.kt  # generated
\`\`\`

## Regenerate everything

\`\`\`
cd ha_resources
npm install
npm run download:ha-icons
\`\`\`

The script:

1. Verifies \`@mdi/svg\` is installed at version \`${EXPECTED_MDI_VERSION}\`.
2. Copies all SVGs to \`svg/\` (gitignored, kept only for local inspection).
3. Converts each \`<path d="..."/>\` into an Android \`VectorDrawable\`
   (24dp/24dp, viewport 24/24, \`fillColor="@android:color/black"\`) in
   \`src/main/res/drawable/ic_mdi_<sanitized-name>.xml\`.
4. Writes \`ha-icons/icons_index.json\` (full \`haIcon → drawable\` index).
5. Writes \`ha-icons/ha_domain_fallback_icons.json\` (HA domain → \`mdi:*\` fallback).
6. Regenerates \`HaIcons.kt\` and \`HaDomainFallbackIcons.kt\`.
7. Verifies that the required icons exist (\`mdi:robot\`, \`mdi:robot-off\`,
   \`mdi:lightbulb\`, \`mdi:palette\`, \`mdi:script-text\`).

## Use

\`\`\`kotlin
import com.anadolstudio.ha_resources.HaIcons
import com.anadolstudio.ha_resources.HaDomainFallbackIcons

val drawableRes: Int? = HaIcons.resolve("mdi:robot")
val fallbackIcon: String? = HaDomainFallbackIcons.resolve("automation") // -> "mdi:robot"
\`\`\`

Hook into your \`:app\`:

\`\`\`kotlin
// app/build.gradle.kts
dependencies {
    implementation(project(":ha_resources"))
}
\`\`\`

## Name mapping rules

| MDI id          | Drawable file              | Drawable name           |
|-----------------|----------------------------|-------------------------|
| \`mdi:robot\`     | \`ic_mdi_robot.xml\`         | \`ic_mdi_robot\`          |
| \`mdi:robot-off\` | \`ic_mdi_robot_off.xml\`     | \`ic_mdi_robot_off\`      |
| \`mdi:numeric-1\` | \`ic_mdi_numeric_1.xml\`     | \`ic_mdi_numeric_1\`      |

Hyphens become underscores; everything else lower-cases. Prefix is always \`ic_mdi_\`.

## Important

Do **not** edit \`HaIcons.kt\`, \`HaDomainFallbackIcons.kt\`, \`icons_index.json\`,
or any \`ic_mdi_*.xml\` by hand — they will be overwritten on the next run.
`;
}

async function ensureCleanDir(dir) {
  await rm(dir, { recursive: true, force: true });
  await mkdir(dir, { recursive: true });
}

async function clearOldMdiDrawables() {
  if (!existsSync(DRAWABLE_OUT_DIR)) {
    await mkdir(DRAWABLE_OUT_DIR, { recursive: true });
    return;
  }
  const entries = await readdir(DRAWABLE_OUT_DIR);
  await Promise.all(
    entries
      .filter((name) => name.startsWith('ic_mdi_') && name.endsWith('.xml'))
      .map((name) => rm(join(DRAWABLE_OUT_DIR, name), { force: true })),
  );
}

async function main() {
  log(`Module dir: ${MODULE_DIR}`);

  const [major] = process.versions.node.split('.').map(Number);
  if (major < 18) {
    fail(`Node.js >= 18 is required (found ${process.versions.node}).`);
  }

  if (!existsSync(NODE_MODULES_MDI_DIR)) {
    fail(
      `@mdi/svg is not installed. Run "npm install" in ${MODULE_DIR} first.`,
    );
  }

  const mdiPkg = JSON.parse(
    await readFile(join(NODE_MODULES_MDI_DIR, 'package.json'), 'utf8'),
  );
  if (mdiPkg.version !== EXPECTED_MDI_VERSION) {
    fail(
      `Expected @mdi/svg@${EXPECTED_MDI_VERSION}, found ${mdiPkg.version}. ` +
        `Fix the version in ha_resources/package.json or in this script.`,
    );
  }
  log(`Using @mdi/svg@${mdiPkg.version}`);

  if (!existsSync(SVG_SRC_DIR)) {
    fail(`No SVG directory inside @mdi/svg package: ${SVG_SRC_DIR}`);
  }

  const allFiles = await readdir(SVG_SRC_DIR);
  const svgFiles = allFiles.filter((f) => f.endsWith('.svg')).sort();
  log(`Found ${svgFiles.length} SVG files in @mdi/svg`);

  await ensureCleanDir(SVG_OUT_DIR);
  await ensureCleanDir(HA_ICONS_DIR);
  await clearOldMdiDrawables();
  await mkdir(KOTLIN_OUT_DIR, { recursive: true });

  const indexEntries = [];
  const drawableEntries = [];
  const skipped = [];
  const seenDrawableNames = new Map(); // drawableName -> haIcon (for collision detection)

  let processed = 0;
  for (const file of svgFiles) {
    const name = file.replace(/\.svg$/, ''); // e.g. "robot-off"
    const haIcon = `mdi:${name}`;
    const sanitized = sanitizeName(name);
    const drawableName = `ic_mdi_${sanitized}`;

    if (!/^[a-z]/.test(drawableName)) {
      skipped.push({ file, reason: `drawable name does not start with a letter: ${drawableName}` });
      continue;
    }

    const existingHa = seenDrawableNames.get(drawableName);
    if (existingHa) {
      skipped.push({
        file,
        reason: `drawable name collision with ${existingHa} -> ${drawableName}`,
      });
      continue;
    }

    const srcPath = join(SVG_SRC_DIR, file);
    const svgText = await readFile(srcPath, 'utf8');
    const d = extractPathD(svgText);
    if (!d) {
      skipped.push({ file, reason: 'no single <path d="..."/> found' });
      continue;
    }

    // Copy raw SVG for local inspection.
    await copyFile(srcPath, join(SVG_OUT_DIR, file));

    // Write VectorDrawable.
    const vd = buildVectorDrawable(d);
    await writeFile(join(DRAWABLE_OUT_DIR, `${drawableName}.xml`), vd, 'utf8');

    seenDrawableNames.set(drawableName, haIcon);

    indexEntries.push({
      haIcon,
      name,
      svgFile: `svg/${file}`,
      androidVectorFile: `src/main/res/drawable/${drawableName}.xml`,
      drawableName,
    });
    drawableEntries.push({ haIcon, drawableName });

    processed++;
    if (processed % 1000 === 0) log(`  ...processed ${processed} icons`);
  }

  log(`Wrote ${processed} VectorDrawable files (${skipped.length} skipped).`);
  if (skipped.length) {
    for (const s of skipped.slice(0, 20)) {
      log(`  skipped ${s.file}: ${s.reason}`);
    }
    if (skipped.length > 20) log(`  ...and ${skipped.length - 20} more.`);
  }

  // Write icons_index.json
  await writeFile(
    join(HA_ICONS_DIR, 'icons_index.json'),
    JSON.stringify(indexEntries, null, 2) + '\n',
    'utf8',
  );
  log(`Wrote ha-icons/icons_index.json (${indexEntries.length} entries).`);

  // Write ha_domain_fallback_icons.json
  await writeFile(
    join(HA_ICONS_DIR, 'ha_domain_fallback_icons.json'),
    JSON.stringify(FALLBACK_DOMAIN_ICONS, null, 2) + '\n',
    'utf8',
  );
  log(`Wrote ha-icons/ha_domain_fallback_icons.json.`);

  // Generate Kotlin
  drawableEntries.sort((a, b) => (a.haIcon < b.haIcon ? -1 : a.haIcon > b.haIcon ? 1 : 0));
  const haIconsKt = buildHaIconsKt(drawableEntries);
  await writeFile(join(KOTLIN_OUT_DIR, 'HaIcons.kt'), haIconsKt, 'utf8');
  log(`Wrote HaIcons.kt (${drawableEntries.length} entries, chunks of ${CHUNK_SIZE}).`);

  const fallbackKt = buildFallbackKt(FALLBACK_DOMAIN_ICONS);
  await writeFile(join(KOTLIN_OUT_DIR, 'HaDomainFallbackIcons.kt'), fallbackKt, 'utf8');
  log(`Wrote HaDomainFallbackIcons.kt.`);

  // README
  await writeFile(README_PATH, buildReadme(processed), 'utf8');
  log(`Wrote README.md.`);

  // Sanity check: required icons must exist.
  const haIconSet = new Set(drawableEntries.map((e) => e.haIcon));
  const missing = REQUIRED_ICONS.filter((n) => !haIconSet.has(`mdi:${n}`));
  if (missing.length) {
    fail(`Required icons are missing: ${missing.map((n) => `mdi:${n}`).join(', ')}`);
  }

  log(`OK: required icons present (${REQUIRED_ICONS.join(', ')})`);
  log(`Generated ${processed} icons from @mdi/svg@${EXPECTED_MDI_VERSION}.`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
